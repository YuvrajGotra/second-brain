import crypto from 'node:crypto';
import { env } from '../../config/env.js';
import { l2Normalize } from '../vectorMath.js';
import { tokenize, splitSentences } from '../textUtils.js';

/**
 * Deterministic, offline provider used by the test-suite and for demoing the app
 * without an API key. Embeddings are hashed bag-of-words + bigram vectors, so
 * texts sharing vocabulary are genuinely close in cosine space; "generation" is
 * extractive (it quotes the most relevant retrieved sentences with citations).
 */
function hashIndex(feature, dims) {
  return crypto.createHash('md5').update(feature).digest().readUInt32LE(0) % dims;
}

function embedText(text) {
  const dims = env.EMBEDDING_DIMENSIONS;
  const vec = new Array(dims).fill(0);
  const tokens = tokenize(text);
  tokens.forEach((t, i) => {
    vec[hashIndex(t, dims)] += 1;
    if (i > 0) vec[hashIndex(`${tokens[i - 1]}_${t}`, dims)] += 0.5;
  });
  if (!tokens.length) vec[0] = 1;
  return l2Normalize(vec);
}

function overlapScore(query, text) {
  const q = new Set(tokenize(query));
  if (!q.size) return 0;
  const t = new Set(tokenize(text));
  let hits = 0;
  for (const tok of q) if (t.has(tok)) hits++;
  return hits / q.size;
}

function mockAnswer({ question, chunks = [] }) {
  if (!chunks.length) {
    return "I couldn't find information about this in your knowledge base. Try uploading a document or note that covers it.";
  }
  const scored = [];
  chunks.forEach((chunk, idx) => {
    for (const sentence of splitSentences(chunk.content)) {
      scored.push({ sentence, n: idx + 1, score: overlapScore(question, sentence) });
    }
  });
  const best = scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);
  if (!best.length) {
    return "I couldn't find information about this in your knowledge base.";
  }
  const lines = best.map((s) => `- ${s.sentence} [${s.n}]`).join('\n');
  return `Based on your knowledge base:\n\n${lines}\n\n_(Generated by the offline mock provider — set AI_PROVIDER=gemini for real answers.)_`;
}

function respond({ task, meta = {} }) {
  switch (task) {
    case 'rewrite': {
      const lastUser = [...(meta.history ?? [])].reverse().find((m) => m.role === 'user');
      const isFollowUp = /\b(it|its|that|this|they|them|those|these)\b/i.test(meta.question);
      return lastUser && isFollowUp ? `${meta.question} (context: ${lastUser.content})` : meta.question;
    }
    case 'rerank':
      return JSON.stringify({ scores: meta.passages.map((p) => Math.round(overlapScore(meta.query, p) * 10)) });
    case 'title':
      return meta.question.split(/\s+/).slice(0, 6).join(' ');
    case 'answer':
    default:
      return mockAnswer(meta);
  }
}

export const mockProvider = {
  name: 'mock',
  chatModel: 'mock-extractive',
  embedDocuments: async (items) => items.map(({ title, text }) => embedText(`${title ?? ''} ${text}`)),
  embedQuery: async (text) => embedText(text),
  generate: async (opts) => respond(opts),
  async *stream(opts) {
    const text = respond(opts);
    for (const piece of text.match(/(\S+\s*){1,3}/g) ?? []) {
      if (!env.isTest) await new Promise((r) => setTimeout(r, 25)); // simulate token streaming
      yield piece;
    }
  },
};
